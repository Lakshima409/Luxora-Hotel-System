// Supports port selection: XAMPP MariaDB=3307, MySQL84=3306
session_start();
$step = 1; $msg = ''; $ok = false;
// probe which ports answer, to pre-select
function probe_port($host, $port) {
  $fp = @fsockopen($host, $port, $errno, $errstr, 2);
  if ($fp) { fclose($fp); return true; }
  return false;
}
$port_hint = '';
foreach ([3307, 3306] as $pp) { if (probe_port('127.0.0.1', $pp)) { $port_hint .= "Port $pp OPEN. "; } else { $port_hint .= "Port $pp closed. "; } }
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
  $host = trim($_POST['host'] ?? '127.0.0.1');
  $port = (int)($_POST['port'] ?? 3307);
  $user = trim($_POST['user'] ?? 'root');
  $pass = $_POST['pass'] ?? '';
  $name = trim($_POST['dbname'] ?? 'hotel_management');
  // fallback: if chosen port fails, try the other one automatically
  $try_ports = [$port, $port === 3307 ? 3306 : 3307];
  $last_err = '';
  foreach ($try_ports as $tp) {
    try {
      $p = new PDO("mysql:host=$host;port=$tp;charset=utf8mb4", $user, $pass, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
      $p->exec("CREATE DATABASE IF NOT EXISTS `$name` CHARACTER SET utf8mb4");
      $p->exec("USE `$name`");
      $sql = file_get_contents(__DIR__ . '/database/schema.sql');
      foreach (array_filter(array_map('trim', explode(';', $sql))) as $stmt) {
        if ($stmt === '') continue;
        try { $p->exec($stmt); } catch (Exception $e) { /* ignore dupes on re-run */ }
      }
      $cfg = "<?php\n// auto-generated by setup.php - DO NOT COMMIT\nputenv('DB_HOST=$host');\nputenv('DB_PORT=$tp');\nputenv('DB_NAME=$name');\nputenv('DB_USER=$user');\nputenv('DB_PASS=" . addslashes($pass) . "');\n";
      file_put_contents(__DIR__ . '/db.local.php', $cfg);
      $n = $p->query("SELECT COUNT(*) FROM users")->fetchColumn();
      $msg = "Success on port $tp! Database '$name' ready with $n users. Credentials saved to db.local.php";
      $ok = true; $step = 2;
      break;
    } catch (Exception $e) { $last_err = "port $tp: " . $e->getMessage(); }
  }
  if (!$ok) $msg = 'Connection failed — tried 3307 then 3306. Last error: ' . $last_err;
}
